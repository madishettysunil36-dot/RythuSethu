export function getDistrictWeather(district: District): WeatherDay[] {
  const offsets: Record<District, number> = {
    Warangal: 0,
    Hanamkonda: 1,
    Karimnagar: 2,
    Khammam: 3,
    Nizamabad: -1,
    Nalgonda: 2,
  };
  const shift = offsets[district];
  const baseDays = [
    {dayLabel: 'Today', date: '2026-11-18', tMin: 21, tMax: 31, hum: 64, wind: 8, rainProb: 10, rainMm: 0},
    {dayLabel: 'Thu', date: '2026-11-19', tMin: 22, tMax: 32, hum: 60, wind: 9, rainProb: 12, rainMm: 0},
    {dayLabel: 'Fri', date: '2026-11-20', tMin: 22, tMax: 30, hum: 76, wind: 18, rainProb: 68, rainMm: 14},
    {dayLabel: 'Sat', date: '2026-11-21', tMin: 21, tMax: 28, hum: 84, wind: 21, rainProb: 78, rainMm: 22},
    {dayLabel: 'Sun', date: '2026-11-22', tMin: 20, tMax: 29, hum: 71, wind: 13, rainProb: 35, rainMm: 3},
    {dayLabel: 'Mon', date: '2026-11-23', tMin: 19, tMax: 30, hum: 58, wind: 7, rainProb: 10, rainMm: 0},
    {dayLabel: 'Tue', date: '2026-11-24', tMin: 19, tMax: 31, hum: 55, wind: 6, rainProb: 5, rainMm: 0},
  ];

  return baseDays.map((d, idx) => {
    const rainProb = Math.min(95, Math.max(5, d.rainProb + (idx === 2 || idx === 3 ? shift * 3 : shift)));
    const wind = Math.max(4, d.wind + (shift % 2));
    const sprayStatus: WeatherDay['sprayStatus'] =
      rainProb >= 50 || wind >= 16 ? 'Hold' : rainProb >= 30 || wind >= 12 ? 'Caution' : 'Safe';
    const sprayReason =
      sprayStatus === 'Hold'
        ? `High wash-off / drift risk (${rainProb}% rain, ${wind} km/h wind)`
        : sprayStatus === 'Caution'
          ? `Spray before 09:00 AM only (${wind} km/h wind)`
          : 'Optimal low-drift morning & evening spray window';
    const irrigationAdvice =
      d.rainMm >= 10
        ? `Skip irrigation — ${d.rainMm} mm expected rainfall`
        : d.tMax >= 31
          ? 'Light evening irrigation recommended (ET0 4.8 mm/day)'
          : 'Maintain soil moisture at field capacity';

    return {
      date: d.date,
      dayLabel: d.dayLabel,
      tempMinC: d.tMin + (shift > 0 ? 1 : 0),
      tempMaxC: d.tMax + (shift > 1 ? 1 : 0),
      humidityPercent: Math.min(92, Math.max(42, d.hum + shift * 2)),
      windKmh: wind,
      rainProbabilityPercent: rainProb,
      rainfallMm: d.rainMm,
      sprayStatus,
      sprayReason,
      irrigationAdvice,
    };
  });
}

